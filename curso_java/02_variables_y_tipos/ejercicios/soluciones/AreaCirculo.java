/* Ejercicio 2 - Area de un circulo. */
public class AreaCirculo {
    public static void main(String[] args) {
        final double PI = 3.14159;
        double radio = 5.0;
        double area = PI * radio * radio;

        System.out.println("Radio: " + radio);
        System.out.println("Area: " + area);
    }
}
