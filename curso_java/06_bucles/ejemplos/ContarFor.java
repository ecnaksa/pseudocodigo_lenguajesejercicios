/*
 * for: contar ascendente y descendente.
 */
public class ContarFor {
    public static void main(String[] args) {
        System.out.print("Ascendente: ");
        for (int i = 1; i <= 10; i++) {
            System.out.print(i + " ");
        }
        System.out.println();

        System.out.print("Descendente: ");
        for (int i = 10; i >= 1; i--) {
            System.out.print(i + " ");
        }
        System.out.println();
    }
}
